bce_logits = nn.BCEWithLogitsLoss()

def dice_loss_from_logits(logits, target, smooth=1e-6):
    pred = torch.sigmoid(logits)

    pred = pred.contiguous().view(-1)
    target = target.contiguous().view(-1)

    intersection = (pred * target).sum()
    dice = (2.0 * intersection + smooth) / (pred.sum() + target.sum() + smooth)
    return 1 - dice

def combined_loss(logits, target):
    bce = bce_logits(logits, target)
    dice = dice_loss_from_logits(logits, target)
    return 0.5 * bce + 0.5 * dice

def dice_score(logits, target, threshold=0.5, smooth=1e-6):
    pred = torch.sigmoid(logits)
    pred = (pred > threshold).float()

    pred = pred.contiguous().view(-1)
    target = target.contiguous().view(-1)

    intersection = (pred * target).sum()
    score = (2.0 * intersection + smooth) / (pred.sum() + target.sum() + smooth)
    return score.item()

