class VesselSegmentationDataset(Dataset):
    def __init__(self, images_dir, annotation_file, transform=None):
        self.images_dir = images_dir
        self.annotation_file = annotation_file
        self.transform = transform

        self.coco = COCO(annotation_file)
        self.image_ids = list(self.coco.imgs.keys())

        self.stenosis_cat_id = 26  # نستبعد stenosis من موديل الشريان

    def __len__(self):
        return len(self.image_ids)

    def __getitem__(self, idx):
        image_id = self.image_ids[idx]
        image_info = self.coco.loadImgs(image_id)[0]
        image_path = os.path.join(self.images_dir, image_info["file_name"])

        image = cv2.imread(image_path)
        if image is None:
            raise FileNotFoundError(f"Image not found: {image_path}")
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        h, w = image.shape[:2]
        mask = np.zeros((h, w), dtype=np.uint8)

        ann_ids = self.coco.getAnnIds(imgIds=image_id)
        anns = self.coco.loadAnns(ann_ids)

        for ann in anns:
            cat_id = ann["category_id"]

            # نستبعد stenosis
            if cat_id == self.stenosis_cat_id:
                continue

            ann_mask = self.coco.annToMask(ann)
            mask = np.maximum(mask, ann_mask.astype(np.uint8))

        if self.transform is not None:
            augmented = self.transform(image=image, mask=mask)
            image = augmented["image"]
            mask = augmented["mask"].float().unsqueeze(0)
        else:
            image = image.astype(np.float32) / 255.0
            image = torch.tensor(image).permute(2, 0, 1).float()
            mask = torch.tensor(mask).unsqueeze(0).float()

        return image, mask

